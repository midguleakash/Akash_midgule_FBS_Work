# 4. Assignment Operators
# Definition
# Used to assign values to variables.
# Operator	Meaning
# =	Assign
# +=	Add and assign
# -=	Subtract and assign
# *=	Multiply and assign
# /=	Divide and assign
# %=	Modulus and assign
# //=	Floor divide and assign
# **=	Power and assign
# Example:
# x = 5
# x += 2   # x = 7
