# A variable is a name (identifier) used to store a value in memory.
# In Python, a variable does not store the actual value — it stores a reference to an object.

# Rules for Identifiers (Only Rules)

# Must start with a letter (a–z, A–Z) or underscore (_)
# Cannot start with a digit
# Cannot use symbol
# Can contain letters, digits, and underscore
# Identifiers are case-sensitive
# cant use keywords as varaibles


